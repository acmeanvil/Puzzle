"""Materials libraries (ADR 0009): Puzzle's generic set plus your own.

Puzzle ships `generic.toml`: a few common materials with typical values. Your own,
fuller library lives outside the repository as a JSON file generated by
`scripts/import_materials.py` (temperature tables, sources). It is read from
PUZZLE_MATERIALS when set (a file, or several separated by os.pathsep), otherwise
from the user data directory (see `user_library_path`). Entries in your library
add to the generic set and replace a generic entry with the same key.

Adding a library material to a project copies it into the project as a static
`Material`: later changes to a library never reach the project, and editing the
project's copy never touches the library.
"""

from __future__ import annotations

import json
import os
import sys
import tomllib
from functools import cache
from importlib.resources import files
from pathlib import Path

from puzzle.model.schema import Material, Project, PropertyTable, Quantity, TablePoint


def user_data_dir() -> Path:
    """Puzzle's per-user data directory on this platform."""
    if sys.platform == "darwin":
        return Path.home() / "Library" / "Application Support" / "Puzzle"
    if os.name == "nt":
        return Path(os.environ.get("APPDATA", Path.home() / "AppData" / "Roaming")) / "Puzzle"
    return Path(os.environ.get("XDG_DATA_HOME", Path.home() / ".local" / "share")) / "puzzle"


def user_library_path() -> Path:
    """Where the importer writes your library by default."""
    return user_data_dir() / "materials" / "library.json"


def library_paths() -> list[Path]:
    """Your library files that exist, in the order they are applied."""
    configured = os.environ.get("PUZZLE_MATERIALS")
    if configured is None:
        paths = [user_library_path()]
    else:  # set but empty: generic materials only (what the tests use)
        paths = [Path(p) for p in configured.split(os.pathsep) if p]
    return [p for p in paths if p.is_file()]


@cache
def _load(paths: tuple[Path, ...]) -> dict[str, dict]:
    entries: dict[str, dict] = {}
    generic = tomllib.loads(files(__package__).joinpath("generic.toml").read_text())
    for key, entry in generic.items():
        entry = dict(entry)
        name, description = entry.pop("name"), entry.pop("description", "")
        sources = entry.pop("sources", [])
        tables = {
            prop: {
                "unit": t["unit"],
                "reference_temperature": t.get("reference_temperature"),
                "points": [[k, v, 0 if sources else None] for k, v in t["points"]],
            }
            for prop, t in entry.pop("tables", {}).items()
        }
        entries[key] = {
            "name": name,
            "description": description,
            "info": {"source": "Puzzle generic library (typical values)"},
            "properties": entry,
            "tables": tables,
            "sources": sources,
        }
    for path in paths:
        entries.update(json.loads(path.read_text())["materials"])
    return entries


def _library() -> dict[str, dict]:
    return _load(tuple(library_paths()))


def library_keys() -> list[str]:
    return sorted(_library())


def search_library(text: str) -> list[str]:
    """Keys whose name, group or specification contains `text` (case-insensitive)."""
    needle = text.lower()
    return [
        key
        for key, e in sorted(_library().items())
        if needle in " ".join([e["name"], *e["info"].values()]).lower()
    ]


def library_material(key: str) -> Material:
    """A fresh Material built from the library entry `key`."""
    try:
        e = _library()[key]
    except KeyError:
        raise KeyError(f"no material '{key}' in the materials library") from None
    tables = {
        prop: PropertyTable(
            unit=t["unit"],
            reference_temperature=t.get("reference_temperature"),
            points=[TablePoint(temperature=k, value=v, source=s) for k, v, s in t["points"]],
        )
        for prop, t in e["tables"].items()
    }
    return Material(
        name=e["name"],
        description=e["description"],
        info=dict(e["info"]),
        properties={prop: Quantity(**q) for prop, q in e["properties"].items()},
        tables=tables,
        sources=list(e["sources"]),
    )


def add_library_material(project: Project, key: str, name: str | None = None) -> Material:
    """Copy a library material into the project and return the project's copy."""
    material = library_material(key)
    if name:
        material.name = name
    return project.add(material)


