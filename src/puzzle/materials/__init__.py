"""Materials libraries (ADR 0009): Puzzle's generic set plus your own.

Puzzle ships `generic.toml`: a few common materials with typical values. Your own,
fuller library lives outside the repository as a JSON file generated by
`scripts/import_materials.py` (temperature tables, sources). It is read from
PUZZLE_MATERIALS when set (a file, or several separated by os.pathsep), otherwise
from the user data directory (see `user_library_path`). Entries in your library
add to the generic set and replace a generic entry with the same key.

Adding a library material to a project copies it into the project as a static
`Material`: later changes to a library never reach the project, and editing the
project's copy never touches the library.
"""

from __future__ import annotations

import json
import os
import sys
import tomllib
from functools import cache
from importlib.resources import files
from pathlib import Path

from puzzle.model.schema import Material, Project, PropertyTable, Quantity, TablePoint


def user_data_dir() -> Path:
    """Puzzle's per-user data directory on this platform (PUZZLE_USER_DIR overrides it:
    tests point it at a scratch folder, so they never read or write a user's files)."""
    if os.environ.get("PUZZLE_USER_DIR"):
        return Path(os.environ["PUZZLE_USER_DIR"])
    if sys.platform == "darwin":
        return Path.home() / "Library" / "Application Support" / "Puzzle"
    if os.name == "nt":
        return Path(os.environ.get("APPDATA", Path.home() / "AppData" / "Roaming")) / "Puzzle"
    return Path(os.environ.get("XDG_DATA_HOME", Path.home() / ".local" / "share")) / "puzzle"


def user_library_path() -> Path:
    """Where the importer writes your library by default."""
    return user_data_dir() / "materials" / "library.json"


def custom_library_path() -> Path:
    """Materials you made or edited in the builder (ADR 0020): kept apart from the
    imported library, so re-importing the spreadsheet never overwrites them."""
    return user_data_dir() / "materials" / "custom.json"


def library_paths() -> list[Path]:
    """Your library files that exist, in the order they are applied."""
    configured = os.environ.get("PUZZLE_MATERIALS")
    if configured is None:
        paths = [user_library_path()]
    else:  # set but empty: generic materials only (what the tests use)
        paths = [Path(p) for p in configured.split(os.pathsep) if p]
    # Your own materials always load last (in the user folder; tests use a scratch one).
    return [p for p in [*paths, custom_library_path()] if p.is_file()]


@cache
def _load(paths: tuple[Path, ...]) -> dict[str, dict]:
    entries: dict[str, dict] = {}
    generic = tomllib.loads(files(__package__).joinpath("generic.toml").read_text())
    for key, entry in generic.items():
        entry = dict(entry)
        name, description = entry.pop("name"), entry.pop("description", "")
        kind = {k: entry.pop(k) for k in ("type", "group") if k in entry}  # how it is grouped
        sources = entry.pop("sources", [])
        tables = {
            prop: {
                "unit": t["unit"],
                "reference_temperature": t.get("reference_temperature"),
                "points": [[k, v, 0 if sources else None] for k, v in t["points"]],
            }
            for prop, t in entry.pop("tables", {}).items()
        }
        entries[key] = {
            "name": name,
            "description": description,
            "info": {"source": "Puzzle generic library (typical values)", **kind},
            "properties": entry,
            "tables": tables,
            "sources": sources,
        }
    for path in paths:
        entries.update(json.loads(path.read_text())["materials"])
    return entries


def _library() -> dict[str, dict]:
    return _load(tuple(library_paths()))


def reload_library() -> None:
    """Forget the cached library (after the builder writes your materials)."""
    _load.cache_clear()


def library_entry(key: str) -> dict:
    """A library entry with its family's values filled in: a variant ("parent": key)
    inherits everything it does not set itself (ADR 0020)."""
    return resolve(_library(), key)


def resolve(lib: dict[str, dict], key: str) -> dict:
    """`library_entry` over a given library (the builder checks an entry this way)."""
    if key not in lib:
        raise KeyError(f"no material '{key}' in the materials library")
    chain, k = [], key
    while k:
        if k in chain:
            raise ValueError(f"material '{key}': its families loop ({' -> '.join(chain)})")
        chain.append(k)
        k = lib.get(k, {}).get("parent")
        if k and k not in lib:
            raise KeyError(f"material '{chain[-1]}': no family '{k}' in the library")
    out: dict = {
        "name": key,
        "description": "",
        "properties": {},
        "tables": {},
        "info": {},
        "sources": [],
        "models": {},
        "solver_keywords": {},
    }
    for k in reversed(chain):  # the family first, then each variant over it
        e = lib[k]
        for part in ("properties", "tables", "info", "models", "solver_keywords"):
            out[part] = {**out[part], **e.get(part, {})}
        out["sources"] = list(dict.fromkeys([*out["sources"], *e.get("sources", [])]))
        for field in ("name", "description", "parent"):
            if field in e:
                out[field] = e[field]
    out["parent"] = lib[key].get("parent")
    return out


def classes() -> dict[str, dict[str, list[str]]]:
    """Type -> group -> family keys (variants stay under their family, `families`):
    how the builder and the material picker lay the library out ("Metal" > "Aluminum")."""
    lib = _library()
    out: dict[str, dict[str, list[str]]] = {}
    for family in families():
        info = lib[family].get("info", {})
        typ = info.get("type") or "Other"
        group = info.get("group") or "Other"
        out.setdefault(typ, {}).setdefault(group, []).append(family)
    order = ["Metal", "Polymer", "Ceramic", "Composite", "Fluid", "Other"]
    return {
        t: dict(sorted(out[t].items(), key=lambda g: (g[0] == "Other", g[0])))
        for t in sorted(out, key=lambda t: (order.index(t) if t in order else len(order), t))
    }


def tree() -> list[tuple[tuple[str, ...], str]]:
    """Every family as (path, key), path = how it is filed: type, group, and in a large
    group the series and alloy from the name ("Metal", "Aluminum", "6xxx", "6061") — so a
    library of hundreds lists as a few headings to open, not one long column."""
    import re

    lib = _library()
    out = []
    for typ, groups in classes().items():
        for group, keys in groups.items():
            names = {k: lib[k]["name"] for k in keys}

            def alloy(name: str) -> str:
                """A 4-digit designation anywhere in the name ("6005A", "Aluminium 6061-T6"),
                else the name's first word."""
                hit = re.search(r"(?<![\d.])(\d{4}[A-Z]?)(?![\d.])", name)
                return hit.group(1) if hit else re.split(r"[-, ]", name.strip(), maxsplit=1)[0]

            alloys = {k: alloy(n) for k, n in names.items()}
            numbered = sum(bool(re.fullmatch(r"\d{4}[A-Z]?", a)) for a in alloys.values())
            for k in sorted(keys, key=lambda k: names[k]):
                path: tuple[str, ...] = (typ, group)
                if len(keys) > 15:
                    a = alloys[k]
                    several = sum(v == a for v in alloys.values()) > 1
                    if numbered > len(keys) / 2 and re.fullmatch(r"\d{4}[A-Z]?", a):
                        path += (f"{a[0]}xxx series",) + ((a,) if several else ())
                    elif several:
                        path += (a,)
                out.append((path, k))
    return out


def families() -> dict[str, list[str]]:
    """Family key -> its variants' keys; a material with no variants is its own family."""
    lib = _library()
    out: dict[str, list[str]] = {}
    for key in sorted(lib):
        parent = lib[key].get("parent")
        if parent:
            out.setdefault(parent, []).append(key)
        else:
            out.setdefault(key, [])
    return out


def library_keys() -> list[str]:
    return sorted(_library())


def search_library(text: str) -> list[str]:
    """Keys whose name, group or specification contains `text` (case-insensitive)."""
    needle = text.lower()
    return [
        key
        for key, e in sorted(_library().items())
        if needle in " ".join([e["name"], *e["info"].values()]).lower()
    ]


def library_material(key: str) -> Material:
    """A fresh Material built from the library entry `key`."""
    return material_from_entry(library_entry(key))


def material_from_entry(e: dict) -> Material:
    """A Material from a resolved library entry."""
    tables = {
        prop: PropertyTable(
            unit=t["unit"],
            reference_temperature=t.get("reference_temperature"),
            points=[TablePoint(temperature=k, value=v, source=s) for k, v, s in t["points"]],
        )
        for prop, t in e["tables"].items()
    }
    return Material(
        name=e["name"],
        description=e["description"],
        info=dict(e["info"]),
        properties={prop: Quantity(**q) for prop, q in e["properties"].items()},
        tables=tables,
        sources=list(e["sources"]),
        models=e.get("models", {}),
        solver_keywords=dict(e.get("solver_keywords", {})),
    )


def add_library_material(project: Project, key: str, name: str | None = None) -> Material:
    """Copy a library material into the project and return the project's copy."""
    material = library_material(key)
    if name:
        material.name = name
    return project.add(material)


