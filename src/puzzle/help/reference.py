"""The help's reference pages, generated from the code's own data (ADR 0083 decision 1),
so they can't drift from it: features, solver settings, capabilities, elements,
operators, material properties, result quantities, Properties fields, problem codes,
MCP tools and CLI commands.

`generate()` gives each page's text; `write()` puts them in `help/reference/`
(`scripts/build_help.py`); `stale()` names the pages that differ from what's written,
which a test refuses. Each entry carries its help key (`<!-- key: ... -->` before its
heading), so F1 and `help.lookup` land on it.
"""

from __future__ import annotations

import argparse
import asyncio
import tempfile
from collections.abc import Callable
from pathlib import Path

from puzzle.help import REFERENCE

GENERATED = "<!-- Generated by scripts/build_help.py from Puzzle's own data: don't edit. -->"


def _front(title: str, order: int, keys: str, summary: str) -> str:
    return (f"---\ntitle: {title}\nsection: reference\norder: {order}\nkeys: {keys}\n"
            f"summary: {summary}\n---\n\n{GENERATED}\n\n")  # fmt: skip


def _cell(text) -> str:
    return str(text).replace("|", "\\|").replace("\n", " ").strip() or " "


def _table(head: list[str], rows: list[list]) -> list[str]:
    if not rows:
        return []
    out = ["| " + " | ".join(head) + " |", "|" + " --- |" * len(head)]
    out += ["| " + " | ".join(_cell(c) for c in r) + " |" for r in rows]
    return [*out, ""]


def _solvers() -> dict[str, str]:
    from puzzle.adapters import SOLVER_NAMES, available_adapters

    return {k: SOLVER_NAMES.get(k, k) for k in sorted(available_adapters())}


def _physics_label(key: str) -> str:
    return key.replace("_", " ").capitalize()


# --- features ---------------------------------------------------------------------------


def features() -> str:
    from puzzle.adapters import available_adapters
    from puzzle.model.catalog import CATALOG

    solvers = _solvers()
    caps = {k: a.capabilities for k, a in available_adapters().items()}
    lines = [_front("Loads, supports and conditions", 10, "feature, kind:feature",
                    "Every load, support and condition a physics offers: what it acts on, "
                    "its values with units and defaults, and the solvers that write it."),
             "Add one from a physics' right-click menu in the model tree (Add feature), "
             "or from Model → Physics and loads. Values are typed in any unit of the "
             "right kind; the defaults are placeholders.", ""]  # fmt: skip
    for physics, specs in CATALOG.items():
        lines += [f"<!-- key: physics:{physics} -->", f"## {_physics_label(physics)}", ""]
        for s in specs:
            takers = [name for k, name in solvers.items()
                      if s.type in caps[k].features and physics in caps[k].physics]  # fmt: skip
            lines += [f"<!-- key: feature:{s.type}, feature:{physics}:{s.type} -->",
                      f"### {s.label}", "",
                      f"Type `{s.type}`, on {'an' if s.entity[0] in 'aeiou' else 'a'} "
                      f"{s.entity} selection. "
                      + (f"Written by {', '.join(takers)}." if takers
                         else "No solver writes it yet."), ""]  # fmt: skip
            lines += _table(
                ["Value", "Default", "Unit"],
                [[f"`{v}`", d, u or "—"] for v, (d, u) in s.values.items()],
            )
    return "\n".join(lines).rstrip() + "\n"


# --- solver settings --------------------------------------------------------------------


def _setting_rows(settings) -> list[str]:
    out = []
    for s in settings:
        choices = ", ".join(f"{label} (`{value}`)" for label, value in s.choices)
        steps = ", ".join(sorted(s.steps)) if s.steps else "every step"
        bits = [
            f"`{s.key}`, the solver's `{s.native}`" if s.native else f"`{s.key}`",
            f"{'an' if s.kind[0] in 'aeiou' else 'a'} {s.kind}",
            f"default {s.default!r}" if s.default is not None else "",
        ]
        if s.unit:
            bits.append(f"in {s.unit}")
        if s.maximum is not None:
            bits.append(f"at most {s.maximum:g}")
        bits.append(f"for {steps}")
        if s.power:
            bits.append("shown at the power-user level")
        out += [f"### {s.label}", "", "; ".join(b for b in bits if b) + "."]
        if choices:
            out.append(f"Choices: {choices}.")
        if s.description:
            out += ["", s.description]
        out.append("")
    return out


def settings() -> str:
    from puzzle.adapters import available_adapters
    from puzzle.adapters.settings import SHARED

    lines = [_front("Solver settings", 20, "setting, settings",
                    "The settings every solver translates, then each solver's own, with "
                    "their native names, defaults and units."),
             "Shared settings live on each solve step; a solver's own settings live on the "
             "study (Properties → Solver settings). Only what is set is written, so a "
             "default never moves a result. Past these, a checked pass-through takes the "
             "solver's own keywords (Expert settings).", "",
             "<!-- key: setting:shared -->", "## Shared by every solver", ""]  # fmt: skip
    for s in SHARED:
        lines.append(f"<!-- key: setting:shared:{s.key}, setting:{s.key} -->")
        lines += _setting_rows([s])
    for key, name in _solvers().items():
        own = available_adapters()[key]().settings_schema()
        lines += [f"<!-- key: setting:{key} -->", f"## {name}", ""]
        if not own:
            lines += [f"{name} has no settings of its own yet.", ""]
        for s in own:
            lines.append(f"<!-- key: setting:{key}:{s.key} -->")
            lines += _setting_rows([s])
    return "\n".join(lines).rstrip() + "\n"


# --- capabilities -----------------------------------------------------------------------


def _shown(value) -> str:
    if isinstance(value, bool):
        return "yes" if value else "no"
    if isinstance(value, (set, frozenset, tuple, list)):
        return ", ".join(sorted(map(str, value))) or "—"
    if isinstance(value, dict):
        return "; ".join(f"{k}: {_shown(v)}" for k, v in sorted(value.items()))
    return str(value)


def capabilities() -> str:
    import dataclasses

    from puzzle.adapters import available_adapters

    lines = [_front("What each solver does", 30, "solver, capability",
                    "Each solver's capability matrix: the physics and analyses it runs, the "
                    "features, contacts, materials and elements it writes."),
             "An adapter claims a capability only once a benchmark for it passes; a study "
             "that asks a solver for something it doesn't write is refused before it runs, "
             "never solved without it (ADR 0006).", ""]  # fmt: skip
    for key, name in _solvers().items():
        adapter = available_adapters()[key]
        caps = adapter.capabilities
        lines += [f"<!-- key: solver:{key}, capability:{key} -->", f"## {name}", ""]
        rows = [[_physics_label(p), _shown(steps)] for p, steps in sorted(caps.physics.items())]
        lines += _table(["Physics", "Analyses"], rows)
        rows = []
        for f in dataclasses.fields(caps):
            if f.name == "physics":
                continue
            value = getattr(caps, f.name)
            if value in (False, frozenset(), set(), (), None, {}):
                continue
            rows.append([f.name.replace("_", " "), _shown(value)])
        lines += _table(["Capability", "Written"], rows)
        lines.append(f"Solve steps per job: {adapter.max_solve_steps or 'any'}.")
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


# --- elements, operators, properties, results, fields, problems -------------------------


def elements() -> str:
    from puzzle import elements as library

    body = library.listing().split("\n", 1)[1].lstrip("\n")  # without its own title
    return _front("Elements", 40, "element, elements",
                  "Every solver's elements, grouped by what they model; a star marks the "
                  "ones Puzzle writes.") + body.rstrip() + "\n"  # fmt: skip


def operators() -> str:
    from puzzle.operators import GROUPS, TYPES, operator_doc

    lines = [_front("Operators", 50, "operator, kind:operator",
                    "Every schematic operator: what it does, an example, what it takes and "
                    "gives."),
             "Add one from the schematic's palette (Tab, or a double-click on the canvas); "
             "wire its inputs from studies, results, parameters or other operators. They "
             "are worked out when you look, never stored.", ""]  # fmt: skip
    by_group: dict[str, list[str]] = {}
    for key, t in TYPES.items():
        by_group.setdefault(t.group, []).append(key)
    for group in [*GROUPS, *sorted(set(by_group) - set(GROUPS))]:
        if group not in by_group:
            continue
        lines += [f"## {group}", ""]
        for key in sorted(by_group[group], key=lambda k: TYPES[k].label):
            d = operator_doc(key)
            lines += [f"<!-- key: operator:{key} -->", f"### {d['name']}", "",
                      f"![The {d['name']} node](image:operator/{key}.png)", "",
                      d["purpose"], ""]  # fmt: skip
            if d["example"]:
                lines += [f"Example: {d['example']}", ""]
            lines += [f"- In: {i['about']}" for i in d["inputs"]]
            lines += [f"- Out: {o['about']}" for o in d["outputs"]]
            if d["also_called"]:
                lines.append(f"- Also found as: {', '.join(d['also_called'])}")
            lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def properties() -> str:
    from puzzle.materials.registry import MODELS, PROPERTIES

    lines = [_front("Material properties", 60, "property, kind:material",
                    "Every material property Puzzle knows, its SI unit and what it is for; "
                    "then the material models."),
             "A material holds single values, tables against temperature where they may "
             "vary, and models (plasticity, Johnson–Cook, ...). The material builder says "
             "which properties a study still lacks, per solver.", ""]  # fmt: skip
    groups: dict[str, list] = {}
    for p in PROPERTIES:
        groups.setdefault(p.group, []).append(p)
    for group, props in groups.items():
        lines += [f"## {group}", ""]
        for p in props:
            lines += [f"<!-- key: property:{p.key} -->", f"### {p.label}", "",
                      f"`{p.key}`, in {p.unit}"
                      + ("; may vary with temperature" if p.table else "") + "."]  # fmt: skip
            if p.help:
                lines += ["", p.help]
            lines.append("")
    lines += ["<!-- key: model -->", "## Material models", ""]
    for key, label in MODELS.items():
        lines += [f"<!-- key: model:{key} -->", f"### {label}", "", f"`{key}`", ""]
    return "\n".join(lines).rstrip() + "\n"


def results() -> str:
    from puzzle.post.quantities import SCALARS, TENSORS, VECTORS

    lines = [_front("Result quantities", 70, "result, kind:result",
                    "Every field a run can store and the results shown from it."),
             "Pick a result in the results bar above the view, or under a run in the model "
             "tree. Vectors give a magnitude and components; tensors give components, "
             "principal values and an equivalent; units follow Settings → Units.", ""]  # fmt: skip
    lines += ["## Vectors", ""]
    for key, (group, (total, prefix), kind) in VECTORS.items():
        lines += [f"<!-- key: result:{key} -->", f"### {group}", "",
                  f"Field `{key}`: {total}, and {prefix} along X, Y and Z"
                  + (f"; a {kind.replace('_', ' ')}." if kind else "."), ""]  # fmt: skip
    lines += ["## Tensors", ""]
    for key, (group, name, kind) in TENSORS.items():
        lines += [f"<!-- key: result:{key} -->", f"### {group}", "",
                  f"Field `{key}`: the {name} components (xx, yy, zz, xy, yz, zx), "
                  "principal values and an equivalent"
                  + (f"; a {kind}." if kind else "."), ""]  # fmt: skip
    lines += ["## Scalars", ""]
    for key, (name, kind) in SCALARS.items():
        lines += [
            f"<!-- key: result:{key} -->",
            f"### {name}",
            "",
            f"Field `{key}`" + (f", a {kind.replace('_', ' ')}." if kind else "."),
            "",
        ]
    return "\n".join(lines).rstrip() + "\n"


def fields() -> str:
    from puzzle.gui.form import DESCRIPTIONS

    lines = [_front("Properties fields", 80, "field",
                    "What each field in the Properties panel and Puzzle's forms means."),
             "F1 on a row of the Properties panel opens its entry here.", ""]  # fmt: skip
    for key in sorted(DESCRIPTIONS):
        lines += [f"<!-- key: field:{key} -->", f"### {key.replace('_', ' ').capitalize()}",
                  "", DESCRIPTIONS[key], ""]  # fmt: skip
    return "\n".join(lines).rstrip() + "\n"


def problems() -> str:
    from puzzle.errors import CODES

    lines = [_front("Problem and error codes", 90, "problem, error, panel:messages",
                    "Every code Puzzle gives a problem, warning or refusal, and what it "
                    "means."),
             "Problems show in the Problems tab and the Advisor before a run; refusals and "
             "warnings name their code, which agents read too.", ""]  # fmt: skip
    for code in sorted(CODES):
        lines += [f"<!-- key: problem:{code}, error:{code} -->", f"### {code}", "",
                  CODES[code][0].upper() + CODES[code][1:] + ".", ""]  # fmt: skip
    return "\n".join(lines).rstrip() + "\n"


# --- MCP tools and the command line -----------------------------------------------------


def mcp_tools() -> str:
    from puzzle.agent.mcp import build_server
    from puzzle.model.schema import Project
    from puzzle.project import save_project

    with tempfile.TemporaryDirectory() as tmp:
        save_project(Project(name="help"), Path(tmp) / "p")
        server = build_server(Path(tmp) / "p", "help")
        tools = asyncio.run(server.list_tools())
    lines = [
        _front(
            "Agent tools (MCP)",
            100,
            "mcp, panel:agent",
            "Every tool Puzzle gives an agent, the built-in one and outside ones "
            "over MCP (`puzzle mcp PROJECT`).",
        ),
        "Model edits go through the same commands the GUI uses, so they appear in the "
        "history, can be undone, and wait for approval at the autonomy level set.",
        "",
    ]
    for t in sorted(tools, key=lambda t: t.name):
        args = sorted((t.input_schema or {}).get("properties", {}))
        lines += [f"<!-- key: mcp:{t.name} -->", f"### {t.name}", "",
                  (t.description or "").strip(), ""]  # fmt: skip
        if args:
            lines += ["Arguments: " + ", ".join(f"`{a}`" for a in args) + ".", ""]
    return "\n".join(lines).rstrip() + "\n"


def cli() -> str:
    from puzzle.cli import _parser

    parser = _parser()
    sub = next(a for a in parser._actions if isinstance(a, argparse._SubParsersAction))
    helps = {c.dest: c.help for c in sub._choices_actions}
    lines = [_front("Command line", 110, "cli",
                    "Every `puzzle` command, what it does and its arguments."),
             "Run `puzzle COMMAND --help` for the same, from the build you have.", ""]  # fmt: skip
    for name in sorted(sub.choices):
        p = sub.choices[name]
        usage = " ".join(p.format_usage().split()[1:])  # without "usage:"
        lines += [f"<!-- key: cli:{name} -->", f"### puzzle {name}", "",
                  (helps.get(name) or p.description or "").strip().rstrip(".") + ".", "",
                  f"`{usage}`", ""]  # fmt: skip
        rows = []
        for a in p._actions:
            if isinstance(a, argparse._HelpAction):
                continue
            label = ", ".join(a.option_strings) or a.dest
            rows.append([f"`{label}`", a.help or ""])
        lines += _table(["Argument", "What"], rows)
    return "\n".join(lines).rstrip() + "\n"


PAGES: dict[str, Callable[[], str]] = {
    "features": features,
    "settings": settings,
    "capabilities": capabilities,
    "elements": elements,
    "operators": operators,
    "properties": properties,
    "results": results,
    "fields": fields,
    "problems": problems,
    "mcp": mcp_tools,
    "cli": cli,
}


def generate() -> dict[str, str]:
    """Each reference page's text, by file name."""
    return {f"{name}.md": make() for name, make in PAGES.items()}


def write(folder: Path = REFERENCE) -> list[str]:
    """Write the pages that changed; their names."""
    folder.mkdir(parents=True, exist_ok=True)
    changed = []
    for name, text in generate().items():
        path = folder / name
        if not path.exists() or path.read_text(encoding="utf-8") != text:
            path.write_text(text, encoding="utf-8", newline="\n")
            changed.append(name)
    return changed


def stale(folder: Path = REFERENCE) -> list[str]:
    """The pages whose written text isn't what the code gives now."""
    return [name for name, text in generate().items()
            if not (folder / name).exists()
            or (folder / name).read_text(encoding="utf-8") != text]  # fmt: skip
